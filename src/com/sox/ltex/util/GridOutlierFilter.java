    private static class Point {
        final double x;
        final double y;
        public ResultMap cellRef = null;

        Point(double x, double y, ResultMap ref) {
            this.x = x;
            this.y = y;
            this.cellRef = ref;
        }

        public GPoint toGPoint() {
            return new GPoint(x, y);
        }

        @Override
        public String toString() {
            return "Point {x=" + x + ", y=" + y + "}";
        }
    }


    private static Point center(List<Point> list) {
        if (list == null || list.isEmpty()) {
            return null;
        }

        double sumX = 0.0;
        double sumY = 0.0;
        for (Point p : list) {
            sumX += p.x;
            sumY += p.y;
        }
        return new Point(sumX / list.size(), sumY / list.size(), null);
    }

    // Cell 리스트에서 Point 리스트로 변환하는 유틸 함수
    private static List<Point> makePointList(ArrayList<ResultMap> cellList) {
        List<Point> points = new ArrayList<>();

        try{
            int limit = cellList.size();
            for (int i = 0; i < limit; i++) {
                ResultMap cell = (ResultMap)cellList.get(i);

                if(cell.get("longtitude") != null && cell.get("latitude") != null) {
                    points.add(new Point(cell.getDouble("longtitude"), cell.getDouble("latitude"), cell));
                }else if(cell.get("longitude") != null && cell.get("latitude") != null){
                    points.add(new Point(cell.getDouble("longitude"), cell.getDouble("latitude"), cell));
                }else{
                    points.add(new Point(cell.getDouble("centerX"), cell.getDouble("centerY"), cell));
                }
            }

        } catch (Exception e) {
            throw new RuntimeException(e);
        }

        return points;
    }



    public static List<List<Point>> pointGroups = null;


    private static GPoint makeSegment(List<Point> points) {

        Point resultCenter = null;
        int discardedCount = 0;

        if (points.isEmpty()) {
            System.out.println("Cell이 없습니다.");
            return resultCenter.toGPoint();
        }

        pointGroups = new ArrayList<>(MAX_GROUP_COUNT);
        // 첫 번째 좌표는 첫 번째 그룹에 추가
        List<Point> firstGroup = new ArrayList<>();
        firstGroup.add(points.get(0));
        pointGroups.add(firstGroup);

        // 두 번째 좌표부터 처리
        for (int i = 1; i < points.size(); i++) {
            Point current = points.get(i);
            double nearestDistance = Double.MAX_VALUE;
            int nearestGroupIndex = -1;

            for (int g = 0; g < pointGroups.size(); g++) {
                Point c = center(pointGroups.get(g));
                if (c == null) {
                    continue;
                }
                double d = CoordTransformUtil.getDistanceBetween(
                        new GPoint(current.x, current.y),
                        new GPoint(c.x, c.y),
                        true
                );
                if (d < nearestDistance) {
                    nearestDistance = d;
                    nearestGroupIndex = g;
                }
            }

            // 모든 그룹 중심과 threshold 초과로 멀면 새 그룹 생성(최대 5개)
            if (nearestDistance > DISTANCE_THRESHOLD || nearestGroupIndex == -1) {
                if (pointGroups.size() < MAX_GROUP_COUNT) {
                    List<Point> newGroup = new ArrayList<>();
                    newGroup.add(current);
                    pointGroups.add(newGroup);
                } else {
                    discardedCount++;
                }
                continue;
            }

            pointGroups.get(nearestGroupIndex).add(current);
        }

        pointGroups.sort((a, b) -> Integer.compare(b.size(), a.size()));

        resultCenter = center(pointGroups.get(0));

        // !! 디버그용 출력
        for (int i = 0; i < pointGroups.size(); i++) {
            List<Point> group = pointGroups.get(i);
            System.out.println("=== group" + (i + 1) + " [" + group.size() + "] ===");
            for (Point p : group) {
                System.out.println(p);
            }
            System.out.println("group" + (i + 1) + " 중심좌표: " + center(group));
        }

        System.out.println("버려진 포인트 수: " + discardedCount);

        MBR groupMbr = getGroupMBR(pointGroups.get(0));
        System.out.println("전체 MBR :  " + groupMbr.toString());

        return  resultCenter.toGPoint();
    }



    public static MBR getGroupMBR(List<Point> pointGroup) {
        if (pointGroup == null || pointGroup.isEmpty()) {
            return null;
        }

        MBR totalMbr = null;

        for (Point point : pointGroup) {
            if (point == null || point.cellRef == null) {
                continue;
            }

            ResultMap cell = point.cellRef;
            if (cell.get("minX") == null || cell.get("minY") == null
                    || cell.get("maxX") == null || cell.get("maxY") == null) {
                continue;
            }

            MBR cellMbr = new MBR(
                    cell.getDouble("minX"),
                    cell.getDouble("minY"),
                    cell.getDouble("maxX"),
                    cell.getDouble("maxY")
            );

            if (totalMbr == null) {
                totalMbr = new MBR(cellMbr);
            } else {
                totalMbr.append(cellMbr);
            }
        }

        return totalMbr;
    }



