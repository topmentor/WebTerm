    private static final double DISTANCE_THRESHOLD = 1000.0;
    private static final int MAX_GROUP_COUNT = 5;



    // @@ 외부에서 ArrayList 형태로 Cell 리스트를 받아서 아웃라이어 제거후 중심좌표를 구하는 함수
    public static GPoint getCenterExOutlier(ArrayList cellList) {

        GPoint result = new GPoint(0,0);

        if(cellList != null){
            List<Point> points = makePointList(cellList);
            result = makeSegment(points);
        }
        return result;
    }



